"""
test_user_manager.py

user_manager.py のテストコードです。ここにも 1 つ問題を仕込んでいます。

SonarQube for IDE はテストコードも解析します。ただし「テストコード専用のルール」と
「どこでも効くルール」は別物で、前者は既定では 1 つも動きません（詳細は末尾のメモ）。

ここで仕込んでいる【3】は後者、つまりファイルの種類に関係なく効くルールなので、
サーバーに繋ぐ前 —— 拡張機能を入れただけの状態で検知されます。

  実行: python3 -m unittest test_user_manager -v
  （標準ライブラリの unittest だけを使っています。pytest は不要です）
"""

import unittest

from user_manager import user_rank


class TestUserRank(unittest.TestCase):
    """user_rank() の判定ロジックを確認する"""

    # ============================================================
    # 【3】いつも成功してしまう assert
    #     ルール: python:S5905
    #            (Assert should not be called on a tuple literal)
    #     → 第 1 段：拡張機能を入れるだけで検知される
    # ============================================================
    #
    # ■ 何が起きているのか
    #
    # よくある誤解は「テストが実行されなくなる」ですが、そうではありません。
    # テストはちゃんと実行されます。assert の行も実行されます。
    # 壊れているのは「何を検査しているか」のほうです。
    #
    # assert は関数ではないので、括弧を付けても引数を囲んだことになりません。
    # 括弧はタプルを作ります。1 行ずつ追うとこうなります。
    #
    #   assert (result["rank"] == "S", "管理者で高得点なら S になるはず")
    #
    #     ① 括弧の中身は評価される
    #        → result["rank"] == "S" は計算され、True か False になる
    #
    #     ② その結果を第 1 要素にしたタプルが組み立てられる
    #        → (False, "管理者で高得点なら S になるはず")
    #
    #     ③ assert が真偽を見るのは、この「タプルそのもの」
    #        → 空でないタプルは常に真
    #        → assert は絶対に失敗しない
    #
    # ①の比較結果は、②で袋に詰められた時点で誰にも見られなくなります。
    # 計算はされているのに、捨てられているわけです。
    #
    # ■ なぜ厄介なのか
    #
    # スキップされたテストなら、レポートに「skipped」と出るので気づけます。
    # これは違います。堂々と PASS します。緑になります。
    # 「テストが 2 件とも通っています」という報告まで、何も嘘はついていません。
    # ただ、そのうち 1 件は何も守っていないだけです。
    #
    # user_rank() の中身を壊してみると、はっきりします。
    # たとえば {"rank": "S"} を {"rank": "Z"} に書き換えても、
    # このテストは落ちません。バグを通してしまいます。
    #
    # Python 自身もコンパイル時に
    #   SyntaxWarning: assertion is always true, perhaps remove parentheses?
    # という警告を出しますが、テストは PASS のままなので、
    # CI のログに流れて誰も見ない、という形で見逃されます。
    # SonarQube for IDE は、これを書いているその場で赤い波線にします。
    #
    # ■ どう直すか
    #
    # 直し方は 3 通りあります。上に行くほど手軽です。
    #
    #   (1) 括弧を 2 文字消す —— これで assert は本来の形に戻る
    #
    #         assert (result["rank"] == "S", "…")   ← いつも成功する
    #         assert result["rank"] == "S", "…"     ← ちゃんと失敗する
    #
    #   (2) unittest を使っているなら self.assertEqual() に書き換える
    #       （下の test_non_numeric_age_... がこの形です）
    #
    #         self.assertEqual(result["rank"], "S", "…")
    #
    #       こちらはそもそも関数なので、括弧を付けても壊れません。
    #       失敗したときに「S を期待したが Z だった」と差分も出ます。
    #       assert より、こちらのほうが安全です。
    #
    #   (3) 直したあと、一度わざとテストを失敗させて確かめる
    #
    #       期待値を "S" から "Z" に変えて実行し、赤くなることを見ます。
    #       落ちなければ、そのテストはまだ何も守っていません。
    #       これは【3】に限らず、テストを書いたときに毎回やる価値があります。

    def test_admin_with_high_score_is_rank_s(self):
        """管理者・18 歳以上・JP・80 点以上なら S ランク"""
        result = user_rank({"role": "admin", "age": "30", "country": "JP", "score": "90"})

        # ↓ 括弧を付けているせいでタプルを assert している。ここが問題のポイント
        assert (result["rank"] == "S", "管理者で高得点なら S になるはず")

    def test_non_numeric_age_is_reported_as_invalid(self):
        """年齢が数値でなければ「不明」を返す（こちらは正しい書き方）"""
        result = user_rank({"role": "admin", "age": "さんじゅう", "score": "90"})

        # ↓ unittest の assertEqual を使っている。失敗すれば必ず落ちる
        self.assertEqual(result["rank"], "不明（数値が不正）")


if __name__ == "__main__":
    unittest.main()


# ============================================================
# メモ：テストコードの解析は、バインドすると変わるのか
# ------------------------------------------------------------
# 結論から言うと、既定のままなら変わりません。理由は 2 つあります。
#
# ① 【3】に使った python:S5905 は scope が "All" のルールです。
#    「テストコードかどうか」を一切見ないので、判定の前提が変わりません。
#
# ② そもそも SonarQube for IDE は、既定では「テストコード」という
#    区別を持っていません。Python アナライザには scope が "Tests" の
#    ルールが 39 個入っていて、うち 37 個は Sonar way で ON なのに、
#    どれも動きません。scope が "Tests" のルールは、テストファイルと
#    判定されたファイルにしか適用されないからです。
#
#    そして何をテストファイルとみなすかは sonarlint.testFilePattern
#    という設定で決まり、その既定値は空 —— 何にもマッチしません。
#    （Java だけは vscode-java のクラスパスから自動判定されます）
#
#    バインドすると、この判定材料はサーバー側の設定（sonar.tests /
#    sonar.test.inclusions）に切り替わります。ただし sonar.tests の
#    既定値も空なので、サーバー側でテストソースを宣言していなければ
#    やはり何も変わりません。
#
# 逆に言うと、テスト専用ルールを働かせたいなら、各自が
#   "sonarlint.testFilePattern": "**/test_*.py,**/*_test.py"
# と設定するか、サーバー側でテストソースを宣言する必要があります。
# 第 1 段から第 2 段へ進むときの構図（設定が届くかどうか）と同じです。
# ============================================================
